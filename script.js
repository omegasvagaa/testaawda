function spring(value, velocity, destination, dt, stiffness, damping) {
  const acceleration = (destination - value) * stiffness;
  velocity = (velocity + acceleration * dt) * Math.exp(-damping * dt);
  value += velocity * dt;
  return [value, velocity];
}
